export type KunciUI = keyof (typeof UI)['id'];

/** Ambil fungsi penerjemah untuk satu bahasa. */
export function pakaiT(lang: Lang) {
  return function t(kunci: KunciUI): string {
    return (UI[lang] as Record<string, string>)[kunci] ?? (UI.id as Record<string, string>)[kunci] ?? kunci;
  };
}
